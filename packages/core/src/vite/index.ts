/// <reference types="node" />
// @kitcms/core/vite: build-time pieces (Node only, never imported by runtime code). Decision 14:
// the SvelteKit Worker also exports the `KitcmsRPC` entrypoint.
//
//   // vite.config.ts
//   import { sveltekit } from '@sveltejs/kit/vite';
//   import { kitcms, kitcmsAdapter } from '@kitcms/core/vite';
//   export default defineConfig({
//     plugins: [sveltekit({ adapter: kitcmsAdapter() }), kitcms()],
//   });
//
// 1. `kitcms()` adds `src/kitcms.rpc.ts` as an extra input of SvelteKit's `ssr` environment, so it
//    is compiled by Vite (aliases, `.svelte` imports) and SHARES CHUNKS with the app: config, the
//    CMS instance and caches are one module graph.
// 2. `kitcmsAdapter()` wraps adapter-cloudflare: it moves the generated worker to
//    `_sveltekit_worker.js`, writes a facade at wrangler `main` that re-exports both the default
//    handler and the RPC entrypoint, and keeps the moved file out of the static assets.
// Verified in Phase 0 locally and in production (§2.2).
//
// OPT-IN dev-time RPC (`kitcms({ devRpc: true })`, off by default, Decision 16):
//   Under `vite dev` SvelteKit SSR runs in Node with adapter-cloudflare's platform proxy, so the
//   `KitcmsRPC` entrypoint is NOT served and a consumer Worker cannot call it. With `devRpc` the
//   plugin adds `@cloudflare/vite-plugin` (`apply: 'serve'`, after `sveltekit()`) running a tiny
//   generated worker (`.svelte-kit/kitcms/dev-rpc-worker.ts`, re-exporting `KitcmsRPC` from your RPC
//   entry) in a second workerd (`rpc` Vite environment) with HMR. The dev wrangler config is your
//   own wrangler config with only `main` (and `assets`) overridden, so D1/R2 bindings are shared.
//   Costs: +0.3-0.5 s dev start, one more workerd, and the site and RPC have SEPARATE module state
//   in dev. `@cloudflare/vite-plugin` is an optional peer dependency: install it yourself, pinned
//   with the same `wrangler` version where possible.
//   Consumer setup (verified): the dev RPC worker registers as `<wrangler name>-rpc` (override with
//   `devRpcName`), NOT under the app's own name: the app's platform proxy registers the app name
//   without the entrypoint and wins, so the consumer then fails with "does not export an entrypoint
//   named KitcmsRPC". So in dev the consumer binds `{ service: "<name>-rpc", entrypoint: "KitcmsRPC" }`.
//   Registry skew: the plugin's miniflare registers in `.../cloudflare/dev-registry/v5`, wrangler
//   4.162 reads `.../.wrangler/registry`. Until versions align, start BOTH processes with the same
//   `CLOUDFLARE_DEV_REGISTRY_PATH=<dir> WRANGLER_REGISTRY_PATH=<dir>`.
import fs from 'node:fs';
import path from 'node:path';
import cloudflare from '@sveltejs/adapter-cloudflare';
import type { Adapter } from '@sveltejs/kit';
import type { Plugin, PluginOption } from 'vite';

export const RPC_ENTRY_NAME = 'kitcms-rpc';
const DEFAULT_RPC_ENTRY = 'src/kitcms.rpc.ts';

export interface KitcmsViteOptions {
	/** The RPC entry module (exports `KitcmsRPC`). Default `src/kitcms.rpc.ts`; `false` disables RPC. */
	rpcEntry?: string | false;
	/**
	 * Serve `KitcmsRPC` under `vite dev` through `@cloudflare/vite-plugin` (see the comment block at
	 * the top of this file). Default false. Requires the optional peer `@cloudflare/vite-plugin`.
	 */
	devRpc?: boolean;
	/** Wrangler config used to derive the dev RPC worker config. Default: wrangler's own lookup. */
	wranglerConfig?: string;
	/** Worker name of the dev RPC worker. Default `<wrangler name>-rpc` (see the header comment). */
	devRpcName?: string;
}

export function kitcms(options: KitcmsViteOptions = {}): PluginOption[] {
	const plugins: PluginOption[] = [rpcEntryPlugin(options)];
	// Order matters: `@cloudflare/vite-plugin` must come AFTER `sveltekit()` (before it, its
	// catch-all middleware swallows every route), and kitcms() is listed after sveltekit().
	if (options.devRpc && options.rpcEntry !== false) plugins.push(devRpcPlugins(options));
	return plugins;
}

/** Loads `@cloudflare/vite-plugin` lazily (only when `devRpc` is on); Vite awaits promised plugins. */
async function devRpcPlugins(options: KitcmsViteOptions): Promise<Plugin[]> {
	const entry = resolveEntry(options);
	if (!entry) {
		throw new Error(`kitcms: devRpc needs an RPC entry (${options.rpcEntry || DEFAULT_RPC_ENTRY})`);
	}
	let mod: typeof import('@cloudflare/vite-plugin');
	try {
		mod = await import('@cloudflare/vite-plugin');
	} catch {
		throw new Error(
			'kitcms: `devRpc: true` needs the optional peer dependency `@cloudflare/vite-plugin` (pnpm add -D @cloudflare/vite-plugin).',
		);
	}
	const dir = path.resolve('.svelte-kit', 'kitcms');
	const worker = path.join(dir, 'dev-rpc-worker.ts');
	fs.mkdirSync(dir, { recursive: true });
	const rel = path.relative(dir, entry).split(path.sep).join('/');
	const source =
		`// Generated by @kitcms/core (devRpc). Do not edit.\n` +
		`export { KitcmsRPC } from ${JSON.stringify(rel)};\n` +
		`export default { fetch: () => new Response('kitcms dev RPC worker', { status: 404 }) };\n`;
	if (!fs.existsSync(worker) || fs.readFileSync(worker, 'utf8') !== source) {
		fs.writeFileSync(worker, source);
	}
	const plugins = mod.cloudflare({
		configPath: options.wranglerConfig,
		viteEnvironment: { name: 'rpc' },
		config: (user) => ({
			name: options.devRpcName ?? `${user.name}-rpc`,
			main: worker,
			assets: undefined,
		}),
	});
	// Dev only: the production build keeps using kitcmsAdapter()'s facade.
	return (Array.isArray(plugins) ? plugins : [plugins]).map((p) => ({ ...p, apply: 'serve' as const }));
}

const KITCMS_PACKAGES = [
	'@kitcms/core',
	'@kitcms/ui',
	'@kitcms/client',
	'@kitcms/plugin-seo',
	'@kitcms/plugin-enquiries',
	'@kitcms/plugin-entitlements',
];

function rpcEntryPlugin(options: KitcmsViteOptions): Plugin {
	let entry: string | undefined;
	return {
		name: 'kitcms:rpc-entry',
		enforce: 'post',
		// One copy of Kit and Svelte, even when @kitcms/* are linked from another checkout
		// (`link:` / workspaces): a second @sveltejs/kit makes thrown `redirect()`/`error()`
		// unrecognisable, so /admin answered 500 instead of redirecting.
		// @kitcms/* ship TypeScript sources, so Vite must compile them as app source, as it already
		// does for workspace links. Installed from npm they'd otherwise be pre-bundled (the Svelte
		// optimizer parses `.svelte.ts` as plain JS, and the SSR optimizer splits core's entries into
		// separate bundles with separate module state) or externalized (Node can't strip types
		// under node_modules).
		// Kit itself stays out of the SSR optimizer too: once the app's own routes import it, Vite
		// pre-bundles `@sveltejs/kit` for SSR while @kitcms/* (compiled as source) keep importing the
		// plain copy. Two Kits again: an admin `redirect()` was an unknown object and sign-in a 500.
		config: () => ({
			resolve: { dedupe: ['@sveltejs/kit', 'svelte'] },
			optimizeDeps: { exclude: KITCMS_PACKAGES },
			ssr: { noExternal: [/^@kitcms\//], optimizeDeps: { exclude: [...KITCMS_PACKAGES, '@sveltejs/kit'] } },
		}),
		configResolved(config) {
			if (options.rpcEntry === false) return;
			const file = path.resolve(config.root, options.rpcEntry ?? DEFAULT_RPC_ENTRY);
			if (fs.existsSync(file)) entry = file;
			else if (options.rpcEntry) throw new Error(`kitcms: RPC entry not found: ${file}`);
		},
		configEnvironment(name, config) {
			if (name !== 'ssr' || !config.build?.rolldownOptions?.input) return;
			const input = config.build.rolldownOptions.input;
			if (typeof input !== 'object' || Array.isArray(input)) {
				throw new Error('kitcms: unexpected SvelteKit SSR input shape (SvelteKit changed?)');
			}
			// configEnvironment runs before configResolved, so resolve the default here too.
			const file = entry ?? resolveEntry(options);
			if (file) input[RPC_ENTRY_NAME] = file;
		},
	};
}

function resolveEntry(options: KitcmsViteOptions): string | undefined {
	if (options.rpcEntry === false) return undefined;
	const file = path.resolve(options.rpcEntry ?? DEFAULT_RPC_ENTRY);
	return fs.existsSync(file) ? file : undefined;
}

type CloudflareAdapterOptions = NonNullable<Parameters<typeof cloudflare>[0]>;

/**
 * adapter-cloudflare + the RPC facade. When the app has no RPC entry, it behaves exactly like
 * adapter-cloudflare.
 */
export function kitcmsAdapter(options: CloudflareAdapterOptions = {}): Adapter {
	// Keep the inner adapter's other hooks (`emulate` = the dev platform proxy, `supports`).
	const inner = cloudflare(options);
	return {
		...inner,
		name: 'kitcms-adapter-cloudflare',
		async adapt(builder) {
			await inner.adapt(builder);

			const rpc = path.join(builder.getServerDirectory(), `${RPC_ENTRY_NAME}.js`);
			if (!fs.existsSync(rpc)) return; // no RPC entry: plain adapter-cloudflare

			const { unstable_readConfig } = (await import('wrangler')) as {
				unstable_readConfig: (a: { config?: string }) => { main?: string };
			};
			const main = unstable_readConfig({ config: options.config }).main;
			if (!main) throw new Error('kitcms: wrangler `main` is required to export KitcmsRPC');
			const dir = path.dirname(main);
			const moved = path.join(dir, '_sveltekit_worker.js');
			fs.renameSync(main, moved);
			const rel = (p: string) => {
				const r = path.relative(dir, p).split(path.sep).join('/');
				return r.startsWith('.') ? r : `./${r}`;
			};
			fs.writeFileSync(
				main,
				`export { default } from ${JSON.stringify(rel(moved))};\n` +
					`export * from ${JSON.stringify(rel(rpc))};\n`,
			);
			// The worker dir may double as the assets dir: never upload the moved file as an asset.
			const ignore = path.join(dir, '.assetsignore');
			if (fs.existsSync(ignore)) fs.appendFileSync(ignore, '\n_sveltekit_worker.js\n');
			else fs.writeFileSync(ignore, '_sveltekit_worker.js\n');
		},
	};
}
