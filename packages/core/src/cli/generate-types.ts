// Pure (no Node APIs): turns a sanitized config into the text of `kitcms-types.d.ts`, the
// document types `@kitcms/client` consumers use (`kitcms<KitcmsTypes>(env.CMS)`).

import type { AnyBlock, AnyField, SanitizedConfig } from '../config/sanitized';

export const TYPES_HEADER = `// This file is generated by \`kitcms generate:types\`. Do not edit it.
// Regenerate it after changing the kitcms config: \`kitcms generate:types\`.
`;

const RESERVED = ['Rel', 'RichTextDoc', 'RichTextNode', 'KitcmsTypes'];

/** `blog post` / `blog-posts` / `metaTitle` → `BlogPost…` / `MetaTitle`. Empty when nothing usable is left. */
export function pascalCase(input: string): string {
	const out = input
		.split(/[^A-Za-z0-9]+/)
		.filter(Boolean)
		.map((w) => w[0]!.toUpperCase() + w.slice(1))
		.join('');
	return /^[0-9]/.test(out) ? `_${out}` : out;
}

const q = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

export function generateTypes(config: SanitizedConfig): string {
	// name → body (null while reserved but not yet generated)
	const bodies = new Map<string, string | null>(RESERVED.map((n) => [n, null]));
	const order: string[] = [];
	let usesRichText = false;

	const reserve = (base: string): string => {
		let name = base;
		for (let i = 2; bodies.has(name); i++) name = `${base}${i}`;
		bodies.set(name, null);
		return name;
	};
	/** Registers an interface; identical bodies under the same base name are shared. */
	const register = (base: string, lines: string[]): string => {
		const body = lines.join('\n');
		for (let i = 1; ; i++) {
			const name = i === 1 ? base : `${base}${i}`;
			if (!bodies.has(name)) {
				bodies.set(name, body);
				order.push(name);
				return name;
			}
			if (bodies.get(name) === body) return name;
		}
	};

	const collectionNames = new Map<string, string>();
	for (const c of config.collections) {
		collectionNames.set(c.slug, reserve(pascalCase(c.labels.singular) || pascalCase(c.slug) || 'Doc'));
	}

	const iface = (name: string, lines: string[]) => (lines.length ? `export interface ${name} {\n${lines.map((l) => `\t${l}`).join('\n')}\n}` : `export interface ${name} {}`);

	const blockNames = new Map<AnyBlock, string>();
	function blockType(block: AnyBlock): string {
		const cached = blockNames.get(block);
		if (cached) return cached;
		const base = `${pascalCase(block.slug) || 'Unnamed'}Block`;
		const name = register(base, [`id: string;`, `blockType: ${q(block.slug)};`, ...fieldLines(block.fields, base)]);
		blockNames.set(block, name);
		return name;
	}

	function fieldType(f: AnyField, parent: string): string {
		switch (f.type) {
			case 'text':
			case 'textarea':
			case 'email':
			case 'slug':
			case 'date':
				return 'string';
			case 'number':
				return 'number';
			case 'checkbox':
				return 'boolean';
			case 'select':
				return f.options.length ? f.options.map((o) => q(o.value)).join(' | ') : 'string';
			case 'json':
				return 'unknown';
			case 'richText':
				usesRichText = true;
				return 'RichTextDoc';
			case 'relationship':
			case 'upload': {
				const rel = `Rel<${q(f.relationTo)}>`;
				return f.hasMany ? `${rel}[]` : rel;
			}
			case 'group': {
				const base = parent + pascalCase(f.name);
				return register(base, fieldLines(f.fields, base));
			}
			case 'array': {
				const base = parent + pascalCase(f.name);
				return `${register(base, [`id: string;`, ...fieldLines(f.fields, base)])}[]`;
			}
			case 'blocks': {
				const names = f.blocks.map(blockType);
				return names.length > 1 ? `(${names.join(' | ')})[]` : names.length ? `${names[0]}[]` : 'never[]';
			}
		}
	}

	function fieldLines(fields: AnyField[], parent: string): string[] {
		return fields.map((f) => {
			const type = fieldType(f, parent);
			const alwaysPresent =
				f.type === 'group' || f.type === 'array' || f.type === 'blocks' || f.type === 'checkbox' || ((f.type === 'relationship' || f.type === 'upload') && f.hasMany);
			const nonNull = alwaysPresent || f.required || (f.type === 'slug' && f.from !== undefined);
			return nonNull ? `${f.name}: ${type};` : `${f.name}?: ${type} | null;`;
		});
	}

	const collectionBodies: string[] = [];
	for (const c of config.collections) {
		const name = collectionNames.get(c.slug)!;
		const lines = ['id: string;', 'createdAt: string;', 'updatedAt: string;', ...fieldLines(c.fields, name)];
		if (c.upload) lines.push('url: string;');
		bodies.set(name, lines.join('\n'));
		collectionBodies.push(iface(name, lines));
	}

	const nested = order.map((n) => iface(n, bodies.get(n)!.split('\n')));

	const parts = [`${TYPES_HEADER}\nimport type { Rel } from '@kitcms/client';\n`];
	if (usesRichText) {
		parts.push(
			`export interface RichTextDoc {\n\ttype: 'doc';\n\tcontent?: RichTextNode[];\n}\n\nexport interface RichTextNode {\n\ttype: string;\n\tattrs?: Record<string, unknown>;\n\tcontent?: RichTextNode[];\n\ttext?: string;\n\tmarks?: { type: string; attrs?: Record<string, unknown> }[];\n}\n`,
		);
	}
	parts.push(...collectionBodies.map((b) => `${b}\n`), ...nested.map((b) => `${b}\n`));
	const entries = config.collections.map((c) => `\t\t${q(c.slug)}: ${collectionNames.get(c.slug)};`);
	parts.push(`export interface KitcmsTypes {\n\tcollections: {\n${entries.join('\n')}\n\t};\n}\n`);
	return parts.join('\n');
}
