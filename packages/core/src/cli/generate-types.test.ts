import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import ts from 'typescript';
import { afterAll, describe, expect, it } from 'vitest';
import { block, collection, defineConfig, global } from '../config/collection';
import { fields as f } from '../config/fields';
import { sanitizeConfig } from '../config/sanitize';
import { generateTypes, pascalCase } from './generate-types';
import { generateTypesFile } from './commands';

const hero = block({ slug: 'hero', fields: { heading: f.text({ required: true }), image: f.upload({ relationTo: 'media' }) } });
const cta = block({ slug: 'cta-banner', fields: { label: f.text(), links: f.array({ fields: { href: f.text({ required: true }) } }) } });

const config = sanitizeConfig(
	defineConfig({
		collections: [
			collection({ slug: 'media', upload: true, fields: { alt: f.text() } }),
			collection({ slug: 'categories', labels: { singular: 'Category' }, fields: { name: f.text({ required: true }) } }),
			collection({
				slug: 'posts',
				fields: {
					title: f.text({ required: true }),
					summary: f.textarea(),
					contact: f.email(),
					handle: f.slug({ from: 'title' }),
					views: f.number(),
					featured: f.checkbox(),
					status: f.select({ options: ['draft', 'published'], required: true }),
					publishedAt: f.date(),
					body: f.richText(),
					extra: f.json(),
					category: f.relationship({ relationTo: 'categories' }),
					related: f.relationship({ relationTo: 'posts', hasMany: true }),
					cover: f.upload({ relationTo: 'media' }),
					seo: f.group({ fields: { metaTitle: f.text(), ogImage: f.upload({ relationTo: 'media' }) } }),
					items: f.array({ fields: { label: f.text({ required: true }), tags: f.array({ fields: { name: f.text() } }) } }),
					layout: f.blocks({ blocks: [hero, cta] }),
				},
			}),
			collection({ slug: 'pages', labels: { singular: 'Landing page' }, fields: { layout: f.blocks({ blocks: [hero] }), title: f.text() } }),
		],
	}),
);

const types = generateTypes(config);

describe('pascalCase', () => {
	it('converts', () => {
		expect(pascalCase('blog-posts')).toBe('BlogPosts');
		expect(pascalCase('Blog post')).toBe('BlogPost');
		expect(pascalCase('metaTitle')).toBe('MetaTitle');
		expect(pascalCase('2fa')).toBe('_2fa');
		expect(pascalCase('--')).toBe('');
	});
});

describe('generateTypes', () => {
	it('is deterministic and has the header', () => {
		expect(generateTypes(config)).toBe(types);
		expect(types.startsWith('// This file is generated by `kitcms generate:types`. Do not edit it.')).toBe(true);
		expect(types).toContain("import type { Rel } from '@kitcms/client';");
	});
	it('names collections, groups, arrays and blocks', () => {
		for (const n of ['Media', 'Category', 'Post', 'LandingPage', 'User', 'PostSeo', 'PostItems', 'PostItemsTags', 'HeroBlock', 'CtaBannerBlock', 'CtaBannerBlockLinks']) {
			expect(types).toMatch(new RegExp(`export interface ${n} \\{`));
		}
		// identical `hero` block is shared by posts and pages
		expect(types.match(/export interface HeroBlock\b/g)).toHaveLength(1);
		expect(types).toContain("'media': Media;");
		expect(types).toContain("'landing-page'".replace('landing-page', 'pages') + ': LandingPage;');
	});
	it('maps field types', () => {
		expect(types).toContain("status: 'draft' | 'published';");
		expect(types).toContain("category?: Rel<'categories'> | null;");
		expect(types).toContain("related: Rel<'posts'>[];");
		expect(types).toContain('featured: boolean;');
		expect(types).toContain('extra?: unknown | null;');
		expect(types).toContain('body?: RichTextDoc | null;');
		expect(types).toContain('handle: string;');
		expect(types).toContain('url: string;');
		expect(types).toContain("layout: (HeroBlock | CtaBannerBlock)[];");
		expect(types.match(/export interface RichTextDoc/g)).toHaveLength(1);
	});
	it('disambiguates blocks with the same slug but different fields', () => {
		const other = block({ slug: 'hero', fields: { title: f.text() } });
		const out = generateTypes(
			sanitizeConfig(
				defineConfig({
					collections: [
						collection({ slug: 'media', upload: true, fields: {} }),
						collection({ slug: 'a', fields: { l: f.blocks({ blocks: [hero] }) } }),
						collection({ slug: 'b', fields: { l: f.blocks({ blocks: [other] }) } }),
					],
				}),
			),
		);
		expect(out).toContain('export interface HeroBlock {');
		expect(out).toContain('export interface HeroBlock2 {');
		expect(out).toContain('l: HeroBlock2[]') ;
	});
	it('emits globals and a `globals` entry', () => {
		const out = generateTypes(
			sanitizeConfig(
				defineConfig({
					collections: [collection({ slug: 'media', upload: true, fields: {} }), collection({ slug: 'pages', fields: { title: f.text() } })],
					globals: [
						global({
							slug: 'site',
							fields: {
								siteName: f.text({ required: true }),
								logo: f.upload({ relationTo: 'media' }),
								nav: f.array({ fields: { label: f.text(), page: f.relationship({ relationTo: 'pages' }) } }),
							},
						}),
					],
				}),
			),
		);
		expect(out).toMatch(/export interface Site \{\n\tid: string;\n\tcreatedAt\?: string;\n\tupdatedAt\?: string;/);
		expect(out).toContain('siteName: string;');
		expect(out).toContain("logo?: Rel<'media'> | null;");
		expect(out).toContain('export interface SiteNav {');
		expect(out).toContain("globals: {\n\t\t'site': Site;\n\t};");
		// no globals → no `globals` key
		expect(types).not.toContain('globals:');
	});
	it('avoids reserved names', () => {
		const out = generateTypes(sanitizeConfig(defineConfig({ collections: [collection({ slug: 'rel', fields: { a: f.text() } })] })));
		expect(out).toContain('export interface Rel2 {');
	});
});

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'kitcms-types-'));
afterAll(() => fs.rmSync(tmp, { recursive: true, force: true }));

function check(files: Record<string, string>): string[] {
	for (const [n, src] of Object.entries(files)) fs.writeFileSync(path.join(tmp, n), src);
	const clientSrc = path.resolve(import.meta.dirname, '../../../client/src/index.ts');
	const program = ts.createProgram(
		Object.keys(files).filter((n) => n.endsWith('.ts') && !n.endsWith('.d.ts')).map((n) => path.join(tmp, n)),
		{
			strict: true,
			noEmit: true,
			target: ts.ScriptTarget.ES2023,
			lib: ['lib.es2023.d.ts'],
			module: ts.ModuleKind.ESNext,
			moduleResolution: ts.ModuleResolutionKind.Bundler,
			skipLibCheck: true,
			noUncheckedIndexedAccess: true,
			types: [],
			paths: { '@kitcms/client': [clientSrc] },
		},
	);
	return ts.getPreEmitDiagnostics(program).map((d) => `${d.file ? path.basename(d.file.fileName) : ''}: ${ts.flattenDiagnosticMessageText(d.messageText, '\n')}`);
}

const USAGE = `
import { kitcms, type KitcmsBinding } from '@kitcms/client';
import type { KitcmsTypes, Post, Media } from './kitcms-types';
declare const binding: KitcmsBinding;
const cms = kitcms<KitcmsTypes>(binding);
export async function ok() {
	const r = await cms.find('posts', {
		where: { status: { equals: 'draft' }, views: { greater_than: 2 }, related: { contains: 'x' }, featured: { equals: true } },
		sort: '-publishedAt',
	});
	const p: Post = r.docs[0]!;
	const deep = await cms.find('posts', { depth: 1 });
	const cover = deep.docs[0]!.cover;
	if (cover && typeof cover !== 'string') {
		const m: Media = cover as Media;
		m.url.toUpperCase();
	}
	const page = await cms.findByID('pages', 'x', { depth: 1 });
	page?.layout[0]?.blockType.toUpperCase();
	const first = p.layout[0]!;
	if (first.blockType === 'cta-banner') first.links[0]?.href.toUpperCase();
	p.seo.metaTitle?.toUpperCase();
	p.items[0]?.tags[0]?.name?.toUpperCase();
	await cms.count('categories');
}
`;

describe('generated types type-check against @kitcms/client', () => {
	it('accepts correct usage and rejects misuse', () => {
		expect(check({ 'kitcms-types.d.ts': types, 'usage.ts': USAGE })).toEqual([]);
		const bad = USAGE + `\nexport const x = () => cms.find('posts', { where: { status: { equals: 'archived' } } });\n`;
		const diags = check({ 'kitcms-types.d.ts': types, 'usage-bad.ts': bad });
		expect(diags).toHaveLength(1);
		expect(diags[0]).toContain('archived');
	});
});

describe('generateTypesFile', () => {
	it('writes once and reports up to date after', async () => {
		const root = path.join(import.meta.dirname, '__fixtures__', '.types-run');
		fs.rmSync(root, { recursive: true, force: true });
		fs.cpSync(path.join(import.meta.dirname, '__fixtures__', 'app'), root, { recursive: true });
		try {
			const logs: string[] = [];
			const ctx = { root, configOption: undefined, remote: false, log: (m: string) => logs.push(m) };
			const a = await generateTypesFile(ctx);
			expect(a.changed).toBe(true);
			expect(fs.readFileSync(path.join(root, 'kitcms-types.d.ts'), 'utf8')).toContain("'posts': Post;");
			expect((await generateTypesFile(ctx, 'out/t.d.ts')).changed).toBe(true);
			expect((await generateTypesFile(ctx)).changed).toBe(false);
			expect(logs).toEqual(['wrote kitcms-types.d.ts', 'wrote out/t.d.ts', 'kitcms-types.d.ts is up to date']);
		} finally {
			fs.rmSync(root, { recursive: true, force: true });
		}
	});
});

describe('generateTypes drafts', () => {
	it('adds `_status` to collections and globals with drafts only', () => {
		const out = generateTypes(
			sanitizeConfig(
				defineConfig({
					collections: [
						collection({ slug: 'pages', versions: { drafts: true }, fields: { title: f.text() } }),
						collection({ slug: 'notes', versions: true, fields: { title: f.text() } }),
					],
					globals: [global({ slug: 'site', versions: { drafts: true }, fields: { name: f.text() } })],
				}),
			),
		);
		expect(out.match(/_status: 'draft' \| 'published';/g)).toHaveLength(2);
		expect(out).toMatch(/interface Page \{[^}]*_status/);
		expect(out).not.toMatch(/interface Note \{[^}]*_status/);
	});
});
