// TableSpec[] → static Drizzle schema source for drizzle-kit (Decision 15). Called from the Node
// CLI, but pure string building. Must produce the same tables as ./drizzle.ts.
import type { ColumnSpec, TableSpec } from './spec';

const IDENT = /^[A-Za-z_$][\w$]*$/;
const ident = (s: string) => (IDENT.test(s) ? s : JSON.stringify(s));

/** One valid, unique JS identifier per table, stable for a given spec list. */
function varNames(specs: TableSpec[]): Map<string, string> {
	const used = new Set<string>();
	const names = new Map<string, string>();
	for (const spec of specs) {
		const base = `t_${spec.name.replace(/\W/g, '_')}`;
		let name = base;
		for (let i = 2; used.has(name); i++) name = `${base}_${i}`;
		used.add(name);
		names.set(spec.name, name);
	}
	return names;
}

export function generateDrizzleSchema(specs: TableSpec[]): string {
	const names = varNames(specs);
	const out = [
		'// GENERATED by kitcms from kitcms.config.ts. Do not edit.',
		"import { index, integer, real, sqliteTable, text, uniqueIndex, type AnySQLiteColumn } from 'drizzle-orm/sqlite-core';",
		'',
	];
	for (const spec of specs) {
		const cols = spec.columns.map((c) => `\t${ident(c.name)}: ${columnSrc(c, names)},`).join('\n');
		const idx = spec.indexes
			.map(
				(ix) =>
					`\t${ix.unique ? 'uniqueIndex' : 'index'}(${JSON.stringify(ix.name)}).on(${ix.columns
						.map((n) => `t[${JSON.stringify(n)}]`)
						.join(', ')}),`,
			)
			.join('\n');
		out.push(
			`export const ${names.get(spec.name)} = sqliteTable(${JSON.stringify(spec.name)}, {\n${cols}\n}, (t) => [\n${idx}\n]);`,
			'',
		);
	}
	return out.join('\n');
}

function columnSrc(c: ColumnSpec, names: Map<string, string>): string {
	const n = JSON.stringify(c.name);
	let s = {
		text: `text(${n})`,
		json: `text(${n}, { mode: 'json' })`,
		real: `real(${n})`,
		integer: `integer(${n})`,
		boolean: `integer(${n}, { mode: 'boolean' })`,
		timestamp: `integer(${n}, { mode: 'timestamp_ms' })`,
	}[c.kind];
	if (c.primaryKey) s += '.primaryKey()';
	if (c.notNull) s += '.notNull()';
	if (c.default !== undefined) s += `.default(${JSON.stringify(c.default)})`;
	if (c.references) {
		const target = names.get(c.references.table);
		if (!target) throw new Error(`Foreign key target table "${c.references.table}" is not in the spec list.`);
		s += `.references((): AnySQLiteColumn => ${target}.${c.references.column}, { onDelete: ${JSON.stringify(c.references.onDelete)} })`;
	}
	return s;
}
